QString defaultUiLanguageId()
{
    return QStringLiteral("ar");
}

QVector<UiLanguageOption> availableUiLanguages()
{
    return {
        UiLanguageOption {QStringLiteral("en"), QStringLiteral("English"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("ar"), QStringLiteral("العربية"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("es"), QStringLiteral("Español"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("fr"), QStringLiteral("Français"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("de"), QStringLiteral("Deutsch"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("tr"), QStringLiteral("Türkçe"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("ru"), QStringLiteral("Русский"), Qt::LeftToRight},
        UiLanguageOption {QStringLiteral("zh_CN"), QStringLiteral("简体中文"), Qt::LeftToRight},
    };
}

QString normalizeUiLanguageId(const QString &languageId)
{
    const QString normalized = languageId.trimmed().toLower();
    for (const auto &option : availableUiLanguages()) {
        if (option.id.toLower() == normalized) {
            return option.id;
        }
    }
    if (normalized == QStringLiteral("es")
        || normalized == QStringLiteral("fr")
        || normalized == QStringLiteral("de")
        || normalized == QStringLiteral("tr")
        || normalized == QStringLiteral("ru")) {
        return normalized;
    }
    return defaultUiLanguageId();
}

void setCurrentUiLanguage(const QString &languageId)
{
    currentLanguageStorage() = normalizeUiLanguageId(languageId);
}

QString currentUiLanguage()
{
    return currentLanguageStorage();
}

Qt::LayoutDirection currentUiLanguageDirection()
{
    for (const auto &option : availableUiLanguages()) {
        if (option.id == currentLanguageStorage()) {
            return option.direction;
        }
    }
    return Qt::LeftToRight;
}

bool hasUiTranslation(const QString &languageId, const QString &sourceText)
{
    const QString normalizedLanguage = normalizeUiLanguageId(languageId);
    return translationsFor(normalizedLanguage).contains(sourceText)
        || supplementalTranslationsFor(normalizedLanguage).contains(sourceText);
}

QString translateUiText(const QString &sourceText)
{
    const QString trimmedSource = sourceText;
    if (trimmedSource.isEmpty()) {
        return sourceText;
    }

    const QString languageId = currentLanguageStorage();
    const auto &primaryTranslations = translationsFor(languageId);
    if (primaryTranslations.contains(trimmedSource)) {
        return primaryTranslations.value(trimmedSource);
    }
    return supplementalTranslationsFor(languageId).value(trimmedSource, sourceText);
}

